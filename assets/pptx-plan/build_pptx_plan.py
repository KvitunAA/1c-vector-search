def svg_header(width: int = 1900, height: int = 1100) -> str:
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
        f'viewBox="0 0 {width} {height}">'
        f'<rect width="{width}" height="{height}" fill="white"/>'
        f'<style>'
        f'.title{{font-family:Arial; font-weight:bold; font-size:80px; fill:{BLUE};}}'
        f'.box{{rx:26; ry:26; stroke-width:3;}}'
        f'.label{{font-family:Arial; font-weight:bold; font-size:68px; fill:{TEXT}; text-anchor:middle;}}'
        f'.small{{font-family:Arial; font-weight:normal; font-size:50px; fill:{TEXT}; text-anchor:middle;}}'
        f'.note{{font-family:Arial; font-weight:bold; font-size:40px; fill:{TEXT};}}'
        f'.arrow{{stroke:{LINE}; stroke-width:3; fill:none; marker-end:url(#arrow);}}'
        f'.thin{{stroke:{LINE}; stroke-width:2.5; fill:none; marker-end:url(#arrow);}}'
        f'</style>'
        f'<defs>'
        f'<marker id="arrow" markerWidth="10" markerHeight="10" refX="8" refY="4" orient="auto">'
        f'<path d="M0,0 L8,4 L0,8 z" fill="{LINE}"/>'
        f'</marker>'
        f'</defs>'
    )

def svg_footer() -> str:
    return "</svg>"

def rect(x: int, y: int, w: int, h: int, fill: str, label: str, sublabel: str | None = None) -> str:
    if sublabel:
        text_y = y + h / 2 - 15
        sub_y = y + h / 2 + 50
    else:
        text_y = y + h / 2 + 20
        sub_y = 0
        
    parts = [
        f'<rect class="box" x="{x}" y="{y}" width="{w}" height="{h}" fill="{fill}" stroke="{BLUE}"/>',
        f'<text class="label" x="{x + w / 2}" y="{text_y}">{label}</text>',
    ]
    if sublabel:
        parts.append(f'<text class="small" x="{x + w / 2}" y="{sub_y}">{sublabel}</text>')
    return "".join(parts)


def line(x1: int, y1: int, x2: int, y2: int, thin: bool = False) -> str:
    cls = "thin" if thin else "arrow"
    return f'<line class="{cls}" x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}"/>'


def write_svg(name: str, body: str, width: int = 1900, height: int = 1100) -> None:
    (ASSETS / name).write_text(svg_header(width, height) + body + svg_footer(), encoding="utf-8")


